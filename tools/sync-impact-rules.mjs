#!/usr/bin/env node
// Copies IMPACT_RULES from web/service-impact.mjs into CheckMicrosoftEndpointsV2.ps1,
// so the web app and the PowerShell script rate unreachable endpoints the same way.
//
//   node tools/sync-impact-rules.mjs          rewrite the block in the script
//   node tools/sync-impact-rules.mjs --check  exit 1 if the script is out of date
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { IMPACT_RULES } from "../web/service-impact.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const psScriptPath = path.join(repoRoot, "CheckMicrosoftEndpointsV2.ps1");
const BEGIN = "# BEGIN GENERATED IMPACT RULES";
const END = "# END GENERATED IMPACT RULES";

function psString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function buildBlock() {
  const lines = [
    BEGIN,
    "# Generated by tools/sync-impact-rules.mjs from web/service-impact.mjs. Do not edit by hand.",
    "# First match wins. Severity: critical = core function stops, degraded = feature missing, low = optional/telemetry.",
    "$endpointImpactRules = @(",
  ];
  IMPACT_RULES.forEach((rule, index) => {
    const separator = index < IMPACT_RULES.length - 1 ? "," : "";
    lines.push(
      `    [PSCustomObject]@{ Id = ${psString(rule.id)}; Area = ${psString(rule.area)}; Feature = ${psString(rule.feature)}; Severity = ${psString(rule.severity)}; Pattern = ${psString(rule.pattern.source)}; Impact = ${psString(rule.impact)} }${separator}`,
    );
  });
  lines.push(")", END);
  return lines.join("\n");
}

const content = await fs.readFile(psScriptPath, "utf-8");
const start = content.indexOf(BEGIN);
const end = content.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`Markers "${BEGIN}" / "${END}" not found in ${psScriptPath}`);
  process.exit(1);
}

const eol = content.includes("\r\n") ? "\r\n" : "\n";
const block = buildBlock().replace(/\n/g, eol);
const updated = content.slice(0, start) + block + content.slice(end + END.length);

if (process.argv.includes("--check")) {
  if (updated !== content) {
    console.error("CheckMicrosoftEndpointsV2.ps1 impact rules are out of date. Run: node tools/sync-impact-rules.mjs");
    process.exit(1);
  }
  console.log("Impact rules are in sync.");
} else if (updated !== content) {
  await fs.writeFile(psScriptPath, updated, "utf-8");
  console.log(`Wrote ${IMPACT_RULES.length} impact rules to CheckMicrosoftEndpointsV2.ps1.`);
} else {
  console.log("Impact rules already up to date.");
}
